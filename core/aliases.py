def display_name(package: str, custom: dict[str, str] | None = None) -> str:
    if custom and package in custom:
        return custom[package]
    if package in BUILTIN_ALIASES:
        return BUILTIN_ALIASES[package]
    leaf = package.rsplit(".", 1)[-1]
    return leaf[:1].upper() + leaf[1:] if leaf else package
